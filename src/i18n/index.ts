type TranslationKeys = keyof typeof translations['pt'];
type Translations = Record<TranslationKeys, string>;

let currentLang: SupportedLang = 'pt';

export function setLang(lang: SupportedLang) {
  currentLang = lang;
}

export function getLang(): SupportedLang {
  return currentLang;
}

/** Main translation function */
export function t(key: TranslationKeys, vars?: Record<string, string | number>): string {
  const langData = (translations[currentLang] as Partial<Translations>) ?? translations['pt'];
  const base     = (translations['pt'] as Translations);
  let   str      = (langData[key] ?? base[key] ?? key) as string;

  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, String(v));
    });
  }

  return str;
}

